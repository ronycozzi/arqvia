import { execFileSync } from "node:child_process";
import { mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const schemaPath = path.join(root, "prisma", "postgresql", "schema.prisma");
const migrationsRoot = path.join(root, "prisma", "postgresql", "migrations");
const baselineDir = path.join(migrationsRoot, "20260713000000_init");
const migrationPath = path.join(baselineDir, "migration.sql");
const prismaCli = path.join(root, "node_modules", "prisma", "build", "index.js");
const configuredDatabaseUrl = process.env.DATABASE_URL || "";
const schemaDatabaseUrl = /^postgres(?:ql)?:\/\//.test(configuredDatabaseUrl)
  ? configuredDatabaseUrl
  : "postgresql://arqvia:arqvia@localhost:5432/arqvia";
const baselineExists = await stat(migrationPath)
  .then(() => true)
  .catch(() => false);

if (baselineExists && process.env.ARQVIA_REGENERATE_BASELINE !== "true") {
  console.log(
    "PostgreSQL baseline already exists. It was left unchanged; use incremental migrations for subsequent schema changes.",
  );
  process.exit(0);
}

const migrationSql = execFileSync(
  process.execPath,
  [
    prismaCli,
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema-datamodel",
    schemaPath,
    "--script",
  ],
  {
    cwd: root,
    encoding: "utf8",
    env: { ...process.env, DATABASE_URL: schemaDatabaseUrl },
  },
);

await mkdir(baselineDir, { recursive: true });
await writeFile(migrationPath, migrationSql, "utf8");
await writeFile(
  path.join(migrationsRoot, "migration_lock.toml"),
  '# Please do not edit this file manually\nprovider = "postgresql"\n',
  "utf8",
);

console.log(`Generated ${path.relative(root, migrationPath)}`);
